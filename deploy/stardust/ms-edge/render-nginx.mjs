// Renders the nginx snippet that carries the fallback base, from sources.json.
//
// Why generate it instead of writing the URL into nginx.conf: the asset fallback and the fonts
// redirect both need the SAME base the sidecar calls its first source, and a second hardcoded copy
// would drift the moment the release pin moves. nginx has no variable-assignment directive, so the
// idiom for a constant is a `map` with only a default.
//
// Run: node deploy/stardust/ms-edge/render-nginx.mjs <out.conf>
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { DEFAULT_CONFIG_PATH, parseSources } from './edge-sidecar.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = process.argv[2] || path.join(here, 'sources-nginx.conf');
const config = parseSources(fs.readFileSync(process.env.SP_EDGE_SOURCES || DEFAULT_CONFIG_PATH, 'utf8'));
const primary = config.order[0];
if (!primary) throw new Error('sources.json: order names no usable source');
const base = config.byId.get(primary);

const body = `# GENERATED by render-nginx.mjs from sources.json — do not edit.
# The primary source (${primary}), for the one place nginx has to know it by itself:
# @sp_asset_fallback answers /assets|fonts/** with this base when the sidecar is down.
# Everything else goes through the sidecar, which reads sources.json at runtime.
map $uri $sp_fallback_base {
    default "${base}";
}
`;

fs.writeFileSync(out, body);
console.log(`sp-edge: wrote ${out} (primary=${primary})`);
